begin;
do $$
declare e public.mt5_telegram_editors; j public.mt5_trade_journal; r jsonb; v jsonb; n integer;
 code_hash text := repeat('d',64); session_hash text := repeat('e',64);
begin
 select * into strict e from public.mt5_telegram_editors where active limit 1;
 select q.* into strict j from public.mt5_trade_journal q where q.account_id=e.account_id and exists(select 1 from public.mt5_deals d where d.account_id=q.account_id and d.position_id=q.position_id and d.deal_type in ('BUY','SELL') and d.deal_entry in ('IN','INOUT')) limit 1;
 r=public.mt5_issue_dashboard_code(code_hash,e.account_id,e.user_id,e.chat_id,9000000000000);
 assert (r->>'valid')::boolean,'issue';
 r=public.mt5_dashboard_editor('login',code_hash,jsonb_build_object('session_hash',session_hash));
 assert (r->>'ok')::boolean,'login';
 r=public.mt5_dashboard_editor('login',code_hash,jsonb_build_object('session_hash',repeat('f',64)));
 assert r->>'error'='unauthorized','code replay';
 r=public.mt5_dashboard_editor('journal',repeat('a',64),jsonb_build_object('journal_id',j.id));
 assert r->>'error'='unauthorized','bad token';
 r=public.mt5_dashboard_editor('journal',session_hash,jsonb_build_object('journal_id',gen_random_uuid()));
 assert r->>'error'='not_found','journal scope';
 r=public.mt5_dashboard_editor('journal',session_hash,jsonb_build_object('journal_id',j.id));
 assert r->'journal'->>'opening_reason' is not distinct from j.opening_reason,'journal read';
 v=jsonb_build_object('journal_id',j.id,'phase','opening','reason','Prueba transaccional; nunca se publica','request_id',gen_random_uuid(),'expected_updated_at',j.updated_at);
 r=public.mt5_dashboard_editor('save',session_hash,v||jsonb_build_object('expected_updated_at','2000-01-01T00:00:00Z'));
 assert r->>'error'='conflict','optimistic concurrency';
 r=public.mt5_dashboard_editor('save',session_hash,v||jsonb_build_object('phase','price'));
 assert r->>'error'='invalid_input','phase whitelist';
 r=public.mt5_dashboard_editor('save',session_hash,v);
 assert (r->>'ok')::boolean,'save';
 r=public.mt5_dashboard_editor('save',session_hash,v);
 assert (r->>'duplicate')::boolean,'idempotent retry';
 r=public.mt5_dashboard_editor('save',session_hash,v||jsonb_build_object('reason','different'));
 assert r->>'error'='invalid_input','request id reuse';
 select count(*) into n from public.mt5_web_reason_audit where request_id=(v->>'request_id')::uuid and previous_reason is not distinct from j.opening_reason;
 assert n=1,'preserve previous reason';
 update public.mt5_telegram_editors set active=false where account_id=e.account_id and user_id=e.user_id and chat_id=e.chat_id;
 r=public.mt5_dashboard_editor('session',session_hash);
 assert r->>'error'='unauthorized','revoked editor';
 update public.mt5_telegram_editors set active=true where account_id=e.account_id and user_id=e.user_id and chat_id=e.chat_id;
 update public.mt5_dashboard_sessions set expires_at=now()-interval '1 second' where hash=session_hash;
 r=public.mt5_dashboard_editor('session',session_hash);
 assert r->>'error'='unauthorized','expired session';
 update public.mt5_dashboard_sessions set expires_at=now()+interval '1 hour' where hash=session_hash;
 r=public.mt5_dashboard_editor('logout',session_hash);
 assert (r->>'ok')::boolean,'logout';
 r=public.mt5_dashboard_editor('session',session_hash);
 assert r->>'error'='unauthorized','revoked session';
 assert not has_function_privilege('anon','public.mt5_dashboard_editor(text,text,jsonb)','EXECUTE'),'anon rpc';
 assert not has_function_privilege('authenticated','public.mt5_issue_dashboard_code(text,text,bigint,bigint,bigint)','EXECUTE'),'client code issue';
 assert not has_table_privilege('anon','public.mt5_web_reason_audit','SELECT'),'private audit';
end $$;
rollback;
